#!/usr/bin/env node
// Managed by @aglaya/ai-kit. PreToolUse hook: blocks AI edits to files that
// must only change through humans or tooling (secrets, lockfiles, git internals).
// Exit code 2 blocks the tool call and shows stderr to the model.

const PROTECTED = [
    { pattern: /(^|\/)\.env(\.(?!example$|sample$)[^/]+)?$/, reason: 'environment files may hold secrets' },
    { pattern: /(^|\/)(package-lock\.json|yarn\.lock|pnpm-lock\.yaml|bun\.lockb?)$/, reason: 'lockfiles are regenerated by the package manager' },
    { pattern: /(^|\/)\.git\//, reason: 'git internals' },
    { pattern: /\.(pem|key|p12)$/, reason: 'private keys' },
];

let input = '';
for await (const chunk of process.stdin) input += chunk;

const filePath = (JSON.parse(input || '{}').tool_input?.file_path ?? '').replaceAll('\\', '/');
const hit = PROTECTED.find(({ pattern }) => pattern.test(filePath));

if (hit) {
    console.error(`Blocked by team policy (@aglaya/ai-kit): ${filePath} (${hit.reason}). Ask a human to make this change.`);
    process.exit(2);
}
